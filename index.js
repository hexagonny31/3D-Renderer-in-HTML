function clear() {
    ctx.fillStyle = BACKGROUND
    ctx.fillRect(0, 0, render.width, render.height)
}

function screen(p) {
    return {
        x: (p.x + 1)/2 * render.width,
        y: (1 - (p.y + 1)/2) * render.height,
    }
}

function point({x, y}) {
    const r = 7
    ctx.fillStyle = FOREGROUND
    ctx.beginPath()
    ctx.arc(x, y, r, 0, Math.PI * 2)
    ctx.fill()
}

function line(p1, p2) {
    ctx.lineWidth = 3
    ctx.strokeStyle = FOREGROUND
    ctx.beginPath()
    ctx.moveTo(p1.x, p1.y)
    ctx.lineTo(p2.x, p2.y)
    ctx.stroke()
}

function face(is) {
    ctx.lineWidth = 2
    ctx.fillStyle = is.color
    ctx.strokeStyle = FOREGROUND
    ctx.beginPath()
    let first = vs[is.f[0]]
    let p = screen(project(transform(first)))
    ctx.moveTo(p.x, p.y)
    for(let i = 1; i < is.f.length; i++) {
        let v = vs[is.f[i]]
        p = screen(project(transform(v)))
        ctx.lineTo(p.x, p.y)
    }
    ctx.closePath()
    ctx.fill()
}

function project({x, y, z}) {
    return {
        x: x/z,
        y: y/z,
    }
}

