function translate_x({x, y, z}, dx) {
    return {x: x + dx, y, z,}
}

function translate_y({x, y, z}, dy) {
    return {x, y: y + dy, z,}
}

function translate_z({x, y, z}, dz) {
    return {x, y, z: z + dz}
}

function rotate_x({x, y, z}, angle) {
    const cos = Math.cos(angle)
    const sin = Math.sin(angle)
    return {
        x,
        y: y*cos-z*sin,
        z: y*sin+z*cos,
    }
}

function rotate_y({x, y, z}, angle) {
    const cos = Math.cos(angle)
    const sin = Math.sin(angle)
    return {
        x: x*cos-z*sin,
        y,
        z: x*sin+z*cos,
    }
}

function rotate_z({x, y, z}, angle) {
    const cos = Math.cos(angle)
    const sin = Math.sin(angle)
    return {
        x: x*cos-y*sin,
        y: x*sin+y*cos,
        z,
    }
}

const FPS = 60
let dz = 0.80
let scale = 0.035
let angle = {x: 0, y: 0, z: 0}
const pivot = {x: 0, y: 8, z: 0}

function transform({x, y, z}) {
    let p = {
        x: (x*scale)-(pivot.x*scale),
        y: (y*scale)-(pivot.y*scale),
        z: (z*scale)-(pivot.z*scale),
    }
    p = rotate_x(p, angle.x)
    p = rotate_y(p, angle.y)
    p = rotate_z(p, angle.z)
    p = translate_z(p, dz)
    return p
}

function frame() {
    const dt = 1/FPS
    // dz += 0.25*dt
    angle.x += 0.3 *Math.PI*dt
    angle.y += 0.25*Math.PI*dt
    angle.z += 0.5 *Math.PI*dt
    clear()

    for(const is of fs) {
        face(is)
    }
    for(const [i, j] of es) {
        const a = transform(vs[i])
        const b = transform(vs[j])
        if(a.z <= 0.1 || b.z <= 0.1) continue
        line(screen(project(a)),
             screen(project(b)),
             a.z, b.z)
    }
    for(const v of vs) {
        tv = transform(v)
        if(tv.z <= 0.1) continue
        point(screen(project(tv)), tv.z)
    }
    setTimeout(frame, 1000/FPS)
}
